"""Turn validated operations into SQL (spec section 2).

Identifiers always go through sql.Identifier and values through sql.Literal, so
nothing from an operation is ever pasted into SQL as raw text. Column types and
default functions are the exception: they are matched against fixed allowlists
in `gate.operations` before they get here.
"""
from __future__ import annotations

from dataclasses import dataclass

from psycopg import sql
from psycopg.types.json import Jsonb

from .operations import DEFAULT_FUNCS, check_expression, ON_DELETE_VALUES, normalize_type
from .conventions import Conventions
from .state import fk_name, index_name, pk_of, ref_column, role_of, unique_name, walk


class UnsafeOp(ValueError):
    """An operation reached SQL generation without passing the gate's checks."""


def _render_check(op: dict, state_before: dict, schema: str = "master") -> sql.Composable:
    """ADD CONSTRAINT ... CHECK, re-verifying the expression here rather than trusting earlier validation."""
    import pglast
    from pglast import ast, enums

    t = op["table"]
    if t not in state_before:
        raise UnsafeOp(f"table {t!r} does not exist")
    problems = check_expression(op["expression"], set(state_before[t]["columns"]))
    if problems:
        raise UnsafeOp("; ".join(problems))
    stmt = (
        sql.SQL("ALTER TABLE {} ADD CONSTRAINT {} CHECK (").format(tbl(t, schema), sql.Identifier(op["name"]))
        + sql.SQL(op["expression"].strip())
        + sql.SQL(")")
    )
    try:
        parsed = pglast.parse_sql(stmt.as_string(None))
        a = parsed[0].stmt
        cons = [c.def_ for c in a.cmds] if len(parsed) == 1 and isinstance(a, ast.AlterTableStmt) else []
        ok = (len(cons) == 1 and isinstance(cons[0], ast.Constraint)
              and cons[0].contype == enums.ConstrType.CONSTR_CHECK and cons[0].conname == op["name"])
    except Exception as exc:  # parse errors and surprises alike are refusals
        raise UnsafeOp(f"check expression could not be rendered safely: {exc}") from exc
    if not ok:
        raise UnsafeOp("check expression could not be rendered safely")
    return stmt


@dataclass
class Stmt:
    sql: sql.Composable
    returning_id: bool = False


def tbl(name: str, schema: str = "master") -> sql.Composed:
    return sql.SQL("{}.{}").format(sql.Identifier(schema), sql.Identifier(name))


def lit(v):
    if isinstance(v, (dict, list)):
        return sql.Literal(Jsonb(v))
    return sql.Literal(v)


def _on_delete(d: dict) -> sql.Composable:
    """ON DELETE clause from an allow-listed value (checked in gate.operations), or nothing."""
    v = d.get("on_delete")
    if v is None:
        return sql.SQL("")
    assert v in ON_DELETE_VALUES
    return sql.SQL(" ON DELETE " + v.upper())


def _col_def(table: str, c: dict, state: dict | None = None, own_cols=None,
             conv: Conventions | None = None, schema: str = "master") -> sql.Composable:
    parts = [sql.Identifier(c["name"]), sql.SQL(normalize_type(c["type"]))]
    if c.get("identity"):
        parts.append(sql.SQL("GENERATED BY DEFAULT AS IDENTITY"))
    if c.get("nullable") is False:
        parts.append(sql.SQL("NOT NULL"))
    if "default" in c:
        d = c["default"]
        parts.append(sql.SQL("DEFAULT"))
        parts.append(sql.SQL(d) if isinstance(d, str) and d in DEFAULT_FUNCS else lit(d))
    if c.get("primary_key"):
        parts.append(sql.SQL("CONSTRAINT {} PRIMARY KEY").format(sql.Identifier(f"{table}_pkey"[:63])))
    if c.get("unique"):
        parts.append(sql.SQL("CONSTRAINT {} UNIQUE").format(sql.Identifier(f"{table}_{c['name']}_key"[:63])))
    ref = c.get("references")
    if ref:
        parts.append(
            sql.SQL("CONSTRAINT {} REFERENCES {} ({}){}").format(
                sql.Identifier(fk_name(table, c["name"])),
                tbl(ref["table"], schema),
                sql.Identifier(ref.get("column") or ref_column(state or {}, ref, conv, table, own_cols)),
                _on_delete(ref),
            )
        )
    return sql.SQL(" ").join(parts)


def _where(where: dict) -> sql.Composable:
    conds = []
    for k, v in where.items():
        if isinstance(v, list):
            conds.append(
                sql.SQL("{} IN ({})").format(sql.Identifier(k), sql.SQL(", ").join(lit(x) for x in v))
            )
        else:
            conds.append(sql.SQL("{} = {}").format(sql.Identifier(k), lit(v)))
    return sql.SQL(" AND ").join(conds)


def _comment_col(table: str, col: str, text: str, schema: str = "master") -> Stmt:
    return Stmt(sql.SQL("COMMENT ON COLUMN {}.{} IS {}").format(tbl(table, schema), sql.Identifier(col), lit(text)))


def statements_for(op: dict, state_before: dict, actor: str | None, conv: Conventions | None = None,
                   schema: str = "master") -> list[Stmt]:
    k = op["op"]
    S = sql.SQL
    I = sql.Identifier

    if k == "create_schema":
        out = [Stmt(S("SELECT singularity.create_managed_schema({})").format(sql.Literal(op["name"])))]
        if op.get("comment"):  # the SQL function has no comment parameter; rw owns the new schema
            out.append(Stmt(S("COMMENT ON SCHEMA {} IS {}").format(I(op["name"]), sql.Literal(op["comment"]))))
        return out

    if k == "rename_schema":
        return [Stmt(S("SELECT singularity.rename_managed_schema({}, {})").format(
            sql.Literal(op["schema"]), sql.Literal(op["new_name"])))]

    if k == "drop_schema":
        return [Stmt(S("SELECT singularity.drop_managed_schema({})").format(sql.Literal(op["schema"])))]

    if k == "create_table":
        name = op["name"]
        defs = S(", ").join(_col_def(name, c, state_before, op["columns"], conv, schema) for c in op["columns"])
        out = [Stmt(S("CREATE TABLE {} ({})").format(tbl(name, schema), defs))]
        if op.get("comment"):
            out.append(Stmt(S("COMMENT ON TABLE {} IS {}").format(tbl(name, schema), lit(op["comment"]))))
        out += [_comment_col(name, c["name"], c["comment"], schema) for c in op["columns"] if c.get("comment")]
        return out

    if k == "add_column":
        c = op["column"]
        out = [Stmt(S("ALTER TABLE {} ADD COLUMN {}").format(tbl(op["table"], schema), _col_def(op["table"], c, state_before, schema=schema)))]
        if c.get("comment"):
            out.append(_comment_col(op["table"], c["name"], c["comment"], schema))
        return out

    if k == "rename_table":
        return [Stmt(S("ALTER TABLE {} RENAME TO {}").format(tbl(op["table"], schema), I(op["new_name"])))]

    if k == "rename_column":
        return [
            Stmt(
                S("ALTER TABLE {} RENAME COLUMN {} TO {}").format(
                    tbl(op["table"], schema), I(op["column"]), I(op["new_name"])
                )
            )
        ]

    if k == "alter_column_type":
        t = S(normalize_type(op["type"]))
        return [
            Stmt(
                S("ALTER TABLE {} ALTER COLUMN {} TYPE {} USING {}::{}").format(
                    tbl(op["table"], schema), I(op["column"]), t, I(op["column"]), t
                )
            )
        ]

    if k == "set_column_comment":
        return [_comment_col(op["table"], op["column"], op["comment"], schema)]

    if k == "add_index":
        name = op.get("name") or index_name(op["table"], op["columns"])
        return [
            Stmt(
                S("CREATE {}INDEX {} ON {} ({})").format(
                    S("UNIQUE ") if op.get("unique") else S(""),
                    I(name),
                    tbl(op["table"], schema),
                    S(", ").join(I(c) for c in op["columns"]),
                )
            )
        ]

    if k == "add_unique":
        name = op.get("name") or unique_name(op["table"], op["columns"])
        return [
            Stmt(
                S("ALTER TABLE {} ADD CONSTRAINT {} UNIQUE ({})").format(
                    tbl(op["table"], schema), I(name), S(", ").join(I(c) for c in op["columns"])
                )
            )
        ]

    if k == "add_foreign_key":
        name = op.get("name") or fk_name(op["table"], op["column"])
        return [
            Stmt(
                S("ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}){}").format(
                    tbl(op["table"], schema), I(name), I(op["column"]),
                    tbl(op["ref_table"], schema), I(op.get("ref_column") or pk_of(state_before, op["ref_table"])),
                    _on_delete(op),
                )
            )
        ]

    if k == "add_check":
        return [Stmt(_render_check(op, state_before, schema))]

    if k == "set_table_comment":
        return [Stmt(S("COMMENT ON TABLE {} IS {}").format(tbl(op["table"], schema), lit(op["comment"])))]

    if k == "drop_column":
        return [Stmt(S("ALTER TABLE {} DROP COLUMN {}").format(tbl(op["table"], schema), I(op["column"])))]

    if k == "drop_table":
        return [Stmt(S("DROP TABLE {}").format(tbl(op["table"], schema)))]

    if k == "drop_index":
        return [Stmt(S("DROP INDEX {}.{}").format(I(schema), I(op["name"])))]

    if k == "drop_constraint":
        return [Stmt(S("ALTER TABLE {} DROP CONSTRAINT {}").format(tbl(op["table"], schema), I(op["name"])))]

    if k == "insert_rows":
        t = op["table"]
        out = []
        for row in op["rows"]:
            row = dict(row)
            by = role_of(state_before, t, "created_by")
            if actor and by and by not in row:
                row[by] = actor
            cols = list(row)
            pk = pk_of(state_before, t)
            has_id = pk is not None
            out.append(
                Stmt(
                    S("INSERT INTO {} ({}) VALUES ({}){}").format(
                        tbl(t, schema),
                        S(", ").join(I(c) for c in cols),
                        S(", ").join(lit(row[c]) for c in cols),
                        S(" RETURNING {}").format(I(pk)) if has_id else S(""),
                    ),
                    returning_id=has_id,
                )
            )
        return out

    if k == "bulk_insert":
        return []  # loaded by schema.executor (COPY + temp table); there is no per-row SQL to show

    if k == "update_rows":
        t = op["table"]
        sets = dict(op["set"])
        upd = role_of(state_before, t, "updated_at")
        if upd and upd not in sets:
            assignments = [S("{} = {}").format(I(c), lit(v)) for c, v in sets.items()]
            assignments.append(S("{} = now()").format(I(upd)))
        else:
            assignments = [S("{} = {}").format(I(c), lit(v)) for c, v in sets.items()]
        return [
            Stmt(
                S("UPDATE {} SET {} WHERE {}").format(tbl(t, schema), S(", ").join(assignments), _where(op["where"]))
            )
        ]

    if k == "deactivate_rows":
        t = op["table"]
        assignments = [S("{} = false").format(I(role_of(state_before, t, "is_active")))]
        upd = role_of(state_before, t, "updated_at")
        if upd:
            assignments.append(S("{} = now()").format(I(upd)))
        return [
            Stmt(S("UPDATE {} SET {} WHERE {}").format(tbl(t, schema), S(", ").join(assignments), _where(op["where"])))
        ]

    raise ValueError(f"no SQL for op {k}")


def plan(ops: list[dict], state: dict, actor: str | None,
         conv: Conventions | None = None, schema: str = "master") -> list[tuple[dict, dict, list[Stmt]]]:
    """[(op, state_before, statements)] for every op, in order."""
    return [(op, before, statements_for(op, before, actor, conv, schema)) for op, before in walk(ops, state, conv)]


def render(ops: list[dict], state: dict, actor: str | None, conv: Conventions | None = None,
           schema: str = "master") -> list[str]:
    """Human-readable SQL for the review screen."""
    out = []
    for _, _, stmts in plan(ops, state, actor, conv, schema):
        out += [s.sql.as_string(None) + ";" for s in stmts]
    return out


def describe(op: dict) -> str:
    """One-line diff entry for the review screen."""
    k = op["op"]
    if k == "create_schema":
        return f"+ create schema {op['name']}"
    if k == "rename_schema":
        return f"~ rename schema {op['schema']} -> {op['new_name']}"
    if k == "drop_schema":
        return f"- drop schema {op['schema']}  (reason: {op['reason']})"
    if k == "create_table":
        cols = ", ".join(f"{c['name']} {normalize_type(c['type'])}" for c in op["columns"])
        return f"+ create table {op['name']} ({cols})"
    if k == "add_column":
        c = op["column"]
        return f"+ add column {op['table']}.{c['name']} {normalize_type(c['type'])}"
    if k == "rename_table":
        return f"~ rename table {op['table']} -> {op['new_name']}"
    if k == "rename_column":
        return f"~ rename column {op['table']}.{op['column']} -> {op['new_name']}"
    if k == "alter_column_type":
        return f"~ change type of {op['table']}.{op['column']} to {normalize_type(op['type'])}"
    if k == "set_column_comment":
        return f"~ set comment on {op['table']}.{op['column']}"
    if k == "add_index":
        u = "unique " if op.get("unique") else ""
        return f"+ add {u}index on {op['table']} ({', '.join(op['columns'])})"
    if k == "add_unique":
        return f"+ add unique constraint on {op['table']} ({', '.join(op['columns'])})"
    if k == "add_foreign_key":
        return f"+ add foreign key {op['table']}.{op['column']} -> {op['ref_table']}.{op.get('ref_column') or '<primary key>'}" + (
            f" on delete {op['on_delete']}" if op.get("on_delete") else "")
    if k == "add_check":
        return f"+ add check {op['name']} on {op['table']}: {op['expression']}"
    if k == "set_table_comment":
        return f"~ set comment on table {op['table']}"
    if k == "drop_column":
        return f"- drop column {op['table']}.{op['column']}  (reason: {op['reason']})"
    if k == "drop_table":
        return f"- drop table {op['table']}  (reason: {op['reason']})"
    if k == "drop_index":
        return f"- drop index {op['name']}  (reason: {op['reason']})"
    if k == "drop_constraint":
        return f"- drop constraint {op['table']}.{op['name']}  (reason: {op['reason']})"
    if k == "insert_rows":
        return f"~ insert {len(op['rows'])} row(s) into {op['table']}"
    if k == "bulk_insert":
        return f"~ bulk load {op['expected_rows']} row(s) into {op['table']} from script {op['source']['script_id']} ({op['source']['stream']})"
    if k == "update_rows":
        return f"~ update {op['table']} set {sorted(op['set'])} where {op['where']}"
    if k == "deactivate_rows":
        return f"~ deactivate rows in {op['table']} where {op['where']}"
    return k
