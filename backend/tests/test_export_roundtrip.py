"""Acceptance test: an exported file loaded with psql into a fresh database reproduces the source."""
import shutil
import subprocess

import pytest

from schema import conn
from schema.export import open_export

from . import pgsetup

if shutil.which("psql") is None:
    pytest.skip("psql is not on PATH; the round trip needs it to load the file", allow_module_level=True)

pytestmark = pytest.mark.usefixtures("master")

DST = "export_roundtrip_dst"

DDL = [
    "CREATE TABLE master.parent ("
    " id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,"
    " name text NOT NULL DEFAULT 'anon',"
    " code text UNIQUE,"
    " qty integer NOT NULL DEFAULT 0 CONSTRAINT parent_qty_nonneg CHECK (qty >= 0),"
    " note text,"
    " is_active boolean NOT NULL DEFAULT true)",
    'CREATE TABLE master."order" ('
    " id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
    ' "we""ird" text,'
    " parent_id integer REFERENCES master.parent(id) ON DELETE CASCADE)",
    "CREATE TABLE master.cyc_a (id integer PRIMARY KEY, b_id integer)",
    "CREATE TABLE master.cyc_b (id integer PRIMARY KEY, a_id integer REFERENCES master.cyc_a(id))",
    "ALTER TABLE master.cyc_a ADD CONSTRAINT cyc_a_b_fk FOREIGN KEY (b_id) REFERENCES master.cyc_b(id)",
    "CREATE TABLE master.tree (id integer PRIMARY KEY, up integer REFERENCES master.tree(id))",
    "CREATE TABLE master.comp (a integer, b integer, label text, PRIMARY KEY (a, b))",
    "CREATE TABLE master.empty_ident (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text)",
    "CREATE INDEX parent_name_idx ON master.parent (name)",
    "CREATE UNIQUE INDEX parent_note_uq ON master.parent (note) WHERE note IS NOT NULL",
    "COMMENT ON TABLE master.parent IS 'the parent table'",
    "COMMENT ON COLUMN master.parent.name IS 'display name'",
    "COMMENT ON COLUMN master.\"order\".\"we\"\"ird\" IS 'odd column'",
]

AWKWARD = ["a\tb", "x\ny", "back\\slash", "\\N", "สวัสดี", "😀", None, ""]

TABLES = ["parent", "order", "cyc_a", "cyc_b", "tree", "comp", "empty_ident"]


def populate():
    with conn.rw_connection(autocommit=True) as c:
        for s in DDL:
            c.execute(s)
        for i, v in enumerate(AWKWARD):
            c.execute(
                "INSERT INTO master.parent (name, code, note, is_active) VALUES (%s, %s, %s, %s)",
                (v if v is not None else "anon", f"c{i}", v, i != 3),
            )
        c.execute('INSERT INTO master."order" (id, "we""ird", parent_id) VALUES (10, %s, 1), (20, NULL, 2)', ("t\tab",))
        c.execute("INSERT INTO master.cyc_a VALUES (1, NULL), (2, NULL)")
        c.execute("INSERT INTO master.cyc_b VALUES (1, 1), (2, 2)")
        c.execute("UPDATE master.cyc_a SET b_id = id")
        c.execute("INSERT INTO master.tree VALUES (1, NULL), (2, 1), (3, 2)")
        c.execute("INSERT INTO master.comp VALUES (1, 1, 'x'), (1, 2, NULL), (2, 1, '')")


def snapshot(dbname):
    """Everything the round trip must preserve, read from `master` in `dbname`."""
    out = {}
    with pgsetup.connect(pgsetup.ADMIN, dbname) as c:
        q = lambda sql, *a: [tuple(r) for r in c.execute(sql, a).fetchall()]  # noqa: E731
        out["columns"] = q(
            "SELECT c.relname, a.attnum, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,"
            " pg_get_expr(d.adbin, d.adrelid), a.attidentity, a.attgenerated, col_description(c.oid, a.attnum)"
            " FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid"
            " JOIN pg_namespace n ON n.oid = c.relnamespace"
            " LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum"
            " WHERE n.nspname = 'master' AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped"
            " ORDER BY c.relname, a.attnum")
        out["constraints"] = q(
            "SELECT c.relname, k.conname, k.contype, pg_get_constraintdef(k.oid) FROM pg_constraint k"
            " JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace"
            " WHERE n.nspname = 'master' ORDER BY c.relname, k.conname")
        out["indexes"] = q(
            "SELECT tablename, indexname, indexdef FROM pg_indexes WHERE schemaname = 'master'"
            " ORDER BY tablename, indexname")
        out["table_comments"] = q(
            "SELECT c.relname, obj_description(c.oid, 'pg_class') FROM pg_class c"
            " JOIN pg_namespace n ON n.oid = c.relnamespace"
            " WHERE n.nspname = 'master' AND c.relkind = 'r' ORDER BY c.relname")
        out["tables"] = [r[0] for r in q(
            "SELECT tablename FROM pg_tables WHERE schemaname = 'master' ORDER BY tablename")]
        rows = {}
        for t in out["tables"]:
            ident = '"master"."' + t.replace('"', '""') + '"'
            rows[t] = tuple(c.execute(
                f"SELECT count(*), md5(coalesce(string_agg(t::text, E'\\n' ORDER BY t::text), '')) FROM {ident} t"
            ).fetchone())
        out["rows"] = rows
    return out


def load(path, dbname):
    return subprocess.run(
        ["psql", "-v", "ON_ERROR_STOP=1", "-q", "-h", pgsetup.HOST, "-p", str(pgsetup.PORT),
         "-U", pgsetup.ADMIN, "-d", dbname, "-f", str(path)],
        capture_output=True, text=True,
    )


@pytest.fixture
def dst():
    with pgsetup.connect(pgsetup.ADMIN, "postgres") as admin:
        admin.execute(f"DROP DATABASE IF EXISTS {DST} WITH (FORCE)")
        admin.execute(f"CREATE DATABASE {DST}")
    yield DST
    pgsetup.drop_db(DST)


def export_to(path, *, data):
    exp = open_export("master", data=data, cap=10_000)
    try:
        with open(path, "wb") as f:
            for chunk in exp.chunks():
                f.write(chunk)
    finally:
        exp.close()


def test_roundtrip_matches_source(dst, tmp_path):
    populate()
    path = tmp_path / "full.sql"
    export_to(path, data=True)
    src = snapshot(pgsetup_src())
    res = load(path, dst)
    assert res.returncode == 0, f"psql failed:\n{res.stderr}"
    got = snapshot(dst)
    for key in src:
        assert got[key] == src[key], f"{key} differs"
    assert src["rows"]["parent"][0] == 8 and src["rows"]["empty_ident"][0] == 0

    with pgsetup.connect(pgsetup.ADMIN, dst) as c:
        assert c.execute("INSERT INTO master.empty_ident (v) VALUES ('n') RETURNING id").fetchone()[0] == 1
        assert c.execute("INSERT INTO master.parent (code) VALUES ('new') RETURNING id").fetchone()[0] == 9
        assert c.execute('INSERT INTO master."order" (parent_id) VALUES (1) RETURNING id').fetchone()[0] == 21


def test_roundtrip_structure_only(dst, tmp_path):
    populate()
    path = tmp_path / "structure.sql"
    export_to(path, data=False)
    src = snapshot(pgsetup_src())
    res = load(path, dst)
    assert res.returncode == 0, f"psql failed:\n{res.stderr}"
    got = snapshot(dst)
    for key in ("columns", "constraints", "indexes", "table_comments", "tables"):
        assert got[key] == src[key], f"{key} differs"
    assert got["tables"] == sorted(TABLES)
    assert all(n == 0 for n, _ in got["rows"].values())


def pgsetup_src():
    from django.conf import settings
    return settings.MASTER_DB["dbname"]
