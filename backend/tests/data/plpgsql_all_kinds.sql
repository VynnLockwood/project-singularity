CREATE FUNCTION f(p int) RETURNS SETOF int LANGUAGE plpgsql AS $$
DECLARE
  a int[] := '{}'; r record; c CURSOR (k int) FOR SELECT k; n int DEFAULT 1; rc refcursor; t text;
BEGIN
  a[1] := 1; n = n + 1;
  IF n > 1 THEN NULL; ELSIF n < 0 THEN NULL; ELSE NULL; END IF;
  CASE n WHEN 1 THEN NULL; ELSE NULL; END CASE;
  CASE WHEN n = 1 THEN NULL; END CASE;
  LOOP EXIT WHEN n > 3; CONTINUE WHEN n = 2; n := n + 1; END LOOP;
  WHILE n < 5 LOOP n := n + 1; END LOOP;
  FOR i IN 1..10 BY 2 LOOP NULL; END LOOP;
  FOR r IN SELECT 1 AS x LOOP NULL; END LOOP;
  FOR r IN c(1) LOOP NULL; END LOOP;
  FOREACH n SLICE 0 IN ARRAY a LOOP NULL; END LOOP;
  PERFORM 1; SELECT 1 INTO n; INSERT INTO t VALUES (1);
  GET DIAGNOSTICS n = ROW_COUNT;
  OPEN rc FOR SELECT 1; FETCH rc INTO n; MOVE rc; CLOSE rc;
  RAISE NOTICE 'x %', n USING HINT = 'h';
  ASSERT n > 0, 'msg';
  CALL p2(n);
  COMMIT; ROLLBACK;
  RETURN;
EXCEPTION WHEN division_by_zero OR SQLSTATE '22012' THEN GET STACKED DIAGNOSTICS t = MESSAGE_TEXT; RAISE;
END $$;
