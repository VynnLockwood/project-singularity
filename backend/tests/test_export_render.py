"""DB-free tests for the DDL renderers. The model shape is what dump_model.read_model returns."""
import datetime

from schema.export import (
    render_foreign_keys, render_header, render_identity_fix, render_indexes, render_structure,
)

INTERNAL = (
    "django_migrations", "auth_user", "accounts_user", "accounts_mcptoken",
    "settings_app_setting", "settings_app_rule", "approvals_change",
    "audit_auditlog", "chat_conversation", "chat_message",
    "duplicates_duplicategroup", "scripts_script", "search_schemaembedding",
    "singularity.",
)


def col(name, type_="text", nullable=True, default=None, identity=None, comment=None):
    return {"name": name, "type": type_, "nullable": nullable, "default": default,
            "identity": identity, "comment": comment}


def table(name, columns, constraints=(), indexes=(), references=(), comment=None):
    return {"name": name, "comment": comment, "columns": list(columns),
            "constraints": list(constraints), "indexes": list(indexes), "references": list(references)}


def con(name, kind, definition):
    return {"name": name, "kind": kind, "definition": definition}


MODEL = {"tables": [
    table("district", [col("district_id", "integer", False, identity="always"),
                       col("province_id", "integer", False)],
          [con("district_pkey", "p", "PRIMARY KEY (district_id)"),
           con("district_province_fk", "f", "FOREIGN KEY (province_id) REFERENCES master.province(province_id)")],
          references=["province"]),
    table("province", [col("province_id", "integer", False, identity="by default"),
                       col("name", "text", True, default="'x'::text", comment="it's a name"),
                       col("code", "text")],
          [con("province_pkey", "p", "PRIMARY KEY (province_id)"),
           con("province_code_key", "u", "UNIQUE (code)"),
           con("province_code_check", "c", "CHECK ((length(code) > 1))")],
          [{"name": "province_name_idx", "definition": "CREATE INDEX province_name_idx ON master.province USING btree (name)"}],
          comment="Provinces"),
]}


def test_create_table_has_identity_default_not_null_and_constraints():
    sql = render_structure(MODEL, "master")
    assert 'CREATE SCHEMA IF NOT EXISTS "master";' in sql
    assert 'SET search_path TO "master";' in sql
    assert 'CREATE TABLE "master"."province"' in sql
    assert '"province_id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL' in sql
    assert '"district_id" integer GENERATED ALWAYS AS IDENTITY NOT NULL' in sql
    assert "DEFAULT 'x'::text" in sql
    assert 'CONSTRAINT "province_pkey" PRIMARY KEY (province_id)' in sql
    assert 'CONSTRAINT "province_code_key" UNIQUE (code)' in sql
    assert 'CONSTRAINT "province_code_check" CHECK ((length(code) > 1))' in sql
    assert "FOREIGN KEY" not in sql
    assert 'COMMENT ON TABLE "master"."province" IS \'Provinces\';' in sql
    assert 'COMMENT ON COLUMN "master"."province"."name" IS \'it\'\'s a name\';' in sql


def test_identifiers_with_quotes_reserved_words_and_case():
    m = {"tables": [
        table("order", [col('we"ird', "integer", False, identity="always"), col("Mixed Case")],
              [con("order_pkey", "p", 'PRIMARY KEY ("we""ird")'),
               con("order_self", "f", 'FOREIGN KEY ("Mixed Case") REFERENCES "Odd Schema"."order"("we""ird")')],
              [{"name": "i", "definition": "CREATE INDEX i ON x"}],
              comment="c")]}
    schema = "Odd Schema"
    structure = render_structure(m, schema)
    assert 'CREATE SCHEMA IF NOT EXISTS "Odd Schema";' in structure
    assert 'SET search_path TO "Odd Schema";' in structure
    assert 'CREATE TABLE "Odd Schema"."order"' in structure
    assert '"we""ird" integer GENERATED ALWAYS AS IDENTITY NOT NULL' in structure
    assert '"Mixed Case" text' in structure
    assert 'COMMENT ON TABLE "Odd Schema"."order"' in structure
    fks = render_foreign_keys(m, schema)
    assert 'ALTER TABLE "Odd Schema"."order" ADD CONSTRAINT "order_self"' in fks
    fix = render_identity_fix(m, schema)
    assert '"Odd Schema"."order"' in fix and '"we""ird"' in fix
    assert "pg_get_serial_sequence('\"Odd Schema\".\"order\"', 'we\"ird')" in fix
    for sql in (structure, fks, fix):
        assert " TABLE order" not in sql and "FROM order" not in sql


def test_single_quotes_in_names_are_doubled_in_serial_sequence_literal():
    m = {"tables": [table("o'brien", [col("i'd", "integer", False, identity="always")])]}
    fix = render_identity_fix(m, "s")
    assert "pg_get_serial_sequence('\"s\".\"o''brien\"', 'i''d')" in fix


def test_comment_literals_escape_quotes():
    m = {"tables": [table("t", [col("a", comment="it's")], comment="o'k")]}
    sql = render_structure(m, "s")
    assert "IS 'it''s';" in sql and "IS 'o''k';" in sql


def test_foreign_keys_after_tables_in_dependency_order():
    fks = render_foreign_keys(MODEL, "master")
    assert fks.count("ADD CONSTRAINT") == 1
    assert ('ALTER TABLE "master"."district" ADD CONSTRAINT "district_province_fk" '
            "FOREIGN KEY (province_id) REFERENCES master.province(province_id);") in fks
    m = {"tables": [
        table("b", [col("x")], [con("b_fk", "f", "FOREIGN KEY (x) REFERENCES a(x)")], references=["a"]),
        table("a", [col("x")], [con("a_fk", "f", "FOREIGN KEY (x) REFERENCES c(x)")], references=["c"]),
        table("c", [col("x")]),
    ]}
    out = render_foreign_keys(m, "s")
    assert out.index('"a_fk"') < out.index('"b_fk"')


def test_fk_cycle_and_self_reference_render_once():
    m = {"tables": [
        table("a", [col("x")], [con("a_b", "f", "FOREIGN KEY (x) REFERENCES b(x)"),
                                con("a_self", "f", "FOREIGN KEY (x) REFERENCES a(x)")], references=["b"]),
        table("b", [col("x")], [con("b_a", "f", "FOREIGN KEY (x) REFERENCES a(x)")], references=["a"]),
    ]}
    fks = render_foreign_keys(m, "s")
    for name in ("a_b", "a_self", "b_a"):
        assert fks.count(f'ADD CONSTRAINT "{name}"') == 1
    assert "FOREIGN KEY" not in render_structure(m, "s")


def test_indexes_and_identity_fix_text():
    idx = render_indexes(MODEL)
    assert idx == "CREATE INDEX province_name_idx ON master.province USING btree (name);\n"
    fix = render_identity_fix(MODEL, "master")
    assert fix.count("setval(") == 2
    assert ('SELECT setval(pg_get_serial_sequence(\'"master"."province"\', \'province_id\'), '
            'COALESCE((SELECT max("province_id") FROM "master"."province"), 1), '
            '(SELECT max("province_id") FROM "master"."province") IS NOT NULL);') in fix
    assert render_indexes({"tables": [table("t", [col("a")])]}) == ""
    assert render_identity_fix({"tables": [table("t", [col("a")])]}, "s") == ""


def test_header_lists_counts_and_data_flag():
    h = render_header("master", True, {"province": 3, "district": 0}, datetime.date(2026, 11, 9))
    assert all(line.startswith("--") for line in h.splitlines() if line)
    assert "master" in h and "2026-11-09" in h and "data: included" in h
    assert "-- province: 3 rows" in h and "-- district: 0 rows" in h
    assert "data: not included" in render_header("master", False, {}, datetime.date(2026, 11, 9))


def test_no_internal_names_leak():
    body = "\n".join([render_header("master", True, {"province": 1}, datetime.date(2026, 1, 1)),
                      render_structure(MODEL, "master"), render_foreign_keys(MODEL, "master"),
                      render_indexes(MODEL), render_identity_fix(MODEL, "master")]).lower()
    assert [n for n in INTERNAL if n in body] == []
