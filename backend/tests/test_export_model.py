"""read_model: the full structure of one schema, read from the catalogs."""
import pytest

from schema import conn
from schema.dump_model import ExportError, allowed_schemas, read_model, table_order

pytestmark = pytest.mark.usefixtures("master")


def build(*statements):
    with conn.rw_connection(autocommit=True) as c:
        for s in statements:
            c.execute(s)


def model():
    with conn.ro_connection() as c:
        return read_model(c, "master")


def by_name(items):
    return {i["name"]: i for i in items}


def test_allowed_schemas_is_master_only():
    assert allowed_schemas() == ["master"]


def test_read_model_columns_defaults_identity_comments():
    build(
        "CREATE TABLE master.item (id integer GENERATED ALWAYS AS IDENTITY, "
        "label text NOT NULL DEFAULT 'x', alt integer GENERATED BY DEFAULT AS IDENTITY, note text)",
        "COMMENT ON TABLE master.item IS 'Items'",
        "COMMENT ON COLUMN master.item.label IS 'The label'",
    )
    (t,) = model()["tables"]
    assert t["name"] == "item" and t["comment"] == "Items"
    cols = by_name(t["columns"])
    assert [c["name"] for c in t["columns"]] == ["id", "label", "alt", "note"]
    assert cols["id"]["identity"] == "always" and cols["id"]["type"] == "integer"
    assert cols["alt"]["identity"] == "by default"
    assert cols["label"]["identity"] is None
    assert cols["label"]["nullable"] is False
    assert cols["label"]["default"] == "'x'::text"
    assert cols["label"]["comment"] == "The label"
    assert cols["note"]["nullable"] is True and cols["note"]["default"] is None
    assert cols["note"]["comment"] is None


def test_constraints_and_indexes():
    build(
        "CREATE TABLE master.parent (id integer PRIMARY KEY)",
        "CREATE TABLE master.child (id integer PRIMARY KEY, code text, qty integer, pid integer, "
        "CONSTRAINT child_code_key UNIQUE (code), CONSTRAINT qty_pos CHECK (qty > 0), "
        "CONSTRAINT child_pid_fk FOREIGN KEY (pid) REFERENCES master.parent(id) ON DELETE CASCADE)",
        "CREATE INDEX child_qty_idx ON master.child (qty)",
        "CREATE UNIQUE INDEX child_pid_qty_uq ON master.child (pid, qty)",
    )
    tables = by_name(model()["tables"])
    child = tables["child"]
    cons = by_name(child["constraints"])
    assert {c["kind"] for c in child["constraints"]} == {"p", "u", "c", "f"}
    assert cons["child_pid_fk"]["kind"] == "f"
    assert "ON DELETE CASCADE" in cons["child_pid_fk"]["definition"]
    assert cons["qty_pos"]["kind"] == "c"
    assert cons["child_code_key"]["kind"] == "u"
    assert sorted(i["name"] for i in child["indexes"]) == ["child_pid_qty_uq", "child_qty_idx"]
    assert all(i["definition"].startswith("CREATE") for i in child["indexes"])
    assert child["references"] == ["parent"]
    assert tables["parent"]["references"] == []
    assert tables["parent"]["indexes"] == []


def test_internal_tables_never_appear():
    build("CREATE TABLE master.thing (id integer)")
    names = [t["name"] for t in model()["tables"]]
    assert names == ["thing"]
    assert not any("django" in n or "singularity" in n for n in names)


def test_zero_column_table_skipped():
    build("CREATE TABLE master.empty ()", "CREATE TABLE master.full (id integer)")
    assert [t["name"] for t in model()["tables"]] == ["full"]


def test_sequence_default_is_a_clear_error():
    build("CREATE TABLE master.seqy (id bigserial PRIMARY KEY)")
    with pytest.raises(ExportError) as ei:
        model()
    assert ei.value.status == 422
    assert '"seqy"."id"' in str(ei.value)


def test_references_and_order():
    build(
        "CREATE TABLE master.a (id integer PRIMARY KEY)",
        "CREATE TABLE master.b (id integer PRIMARY KEY, a_id integer REFERENCES master.a(id))",
        "CREATE TABLE master.c (id integer PRIMARY KEY, b_id integer REFERENCES master.b(id))",
    )
    m = model()
    assert table_order(m) == ["a", "b", "c"]


def test_cycle_and_self_reference_terminate():
    build(
        "CREATE TABLE master.x (id integer PRIMARY KEY, y_id integer)",
        "CREATE TABLE master.y (id integer PRIMARY KEY, x_id integer REFERENCES master.x(id))",
        "ALTER TABLE master.x ADD FOREIGN KEY (y_id) REFERENCES master.y(id)",
        "CREATE TABLE master.z (id integer PRIMARY KEY, parent_id integer REFERENCES master.z(id))",
        "CREATE TABLE master.a (id integer PRIMARY KEY)",
    )
    m = model()
    assert by_name(m["tables"])["z"]["references"] == []
    order = table_order(m)
    assert sorted(order) == ["a", "x", "y", "z"] and len(order) == 4
    assert order == ["a", "z", "x", "y"]


def test_table_order_is_pure_and_alphabetical():
    m = {"tables": [
        {"name": "b", "references": []}, {"name": "a", "references": ["c"]}, {"name": "c", "references": []},
    ]}
    assert table_order(m) == ["b", "c", "a"]
    cyc = {"tables": [
        {"name": "q", "references": ["p"]}, {"name": "p", "references": ["q"]}, {"name": "r", "references": []},
    ]}
    assert table_order(cyc) == ["r", "p", "q"]


