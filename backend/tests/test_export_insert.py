"""The default export is plain SQL that any client runs (INSERT); COPY stays as the fast psql-only choice.

Also: one transaction (a failed or cut-off run leaves nothing), batched stream (no chunk per row), and a
cap on how many data exports run at once.
"""
import math

import pytest

from schema import conn
from schema.dump_model import ExportError
from schema.export import BATCH_BYTES, INSERT_ROWS, MAX_CONCURRENT_EXPORTS, open_export

from . import pgsetup

pytestmark = [pytest.mark.django_db(transaction=True), pytest.mark.usefixtures("master")]


def build(*statements):
    with conn.rw_connection(autocommit=True) as c:
        for s in statements:
            c.execute(s)


def export(fmt="insert", data=True, cap=10**7):
    ex = open_export("master", data=data, cap=cap, fmt=fmt)
    try:
        return b"".join(ex.chunks()).decode()
    finally:
        ex.close()


def admin():
    """The owner role, like the person who restores a file; same database as the app."""
    with conn.rw_connection(autocommit=True) as c:
        name = c.info.dbname
    return pgsetup.connect(pgsetup.ADMIN, name)


def run_as_plain_sql(text):
    """What a SQL editor does: send the whole file as SQL, no stdin, no psql meta-commands."""
    with admin() as c:
        c.execute(text)
        for (name,) in c.execute("SELECT tablename FROM pg_tables WHERE schemaname = 'master'").fetchall():
            c.execute(f'ALTER TABLE master."{name}" OWNER TO singularity_master_rw')    # so the test cleanup can drop it


def rows(sql):
    with admin() as c:
        return [tuple(r) for r in c.execute(sql).fetchall()]


def drop(*tables):
    build(*[f'DROP TABLE IF EXISTS master."{t}" CASCADE' for t in tables])


def seed():
    build(
        "CREATE TABLE master.parent (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)",
        "CREATE TABLE master.child (id integer PRIMARY KEY, pid integer REFERENCES master.parent(id), "
        "is_active boolean NOT NULL DEFAULT true)",
        "INSERT INTO master.parent (name) VALUES ('a'), ('b')",
        "INSERT INTO master.child VALUES (1, 1, true), (2, 2, false)",
    )


def test_default_is_insert_and_has_no_copy_block():
    seed()
    out = export()
    assert "COPY " not in out and "FROM stdin" not in out and "\\." not in out
    assert 'INSERT INTO "master"."parent" ("id", "name")' in out
    assert "-- format: insert" in out


def test_the_file_runs_as_plain_sql_and_restores_everything():
    seed()
    before = (rows("SELECT * FROM master.parent ORDER BY id"), rows("SELECT * FROM master.child ORDER BY id"))
    out = export()
    drop("child", "parent")
    run_as_plain_sql(out)                                           # this is the case that failed with COPY
    assert (rows("SELECT * FROM master.parent ORDER BY id"), rows("SELECT * FROM master.child ORDER BY id")) == before
    assert rows("INSERT INTO master.parent (name) VALUES ('c') RETURNING id") == [(3,)]    # identity carries on


AWKWARD = ["a\tb", "x\ny", "back\\slash", "\\N", "it's", "'; DROP TABLE x; --", "สวัสดี", "😀", None, "", "NULL", "-- c"]


def test_values_of_every_kind_survive_the_round_trip():
    build(
        "CREATE TABLE master.kinds (id integer PRIMARY KEY, t text, n numeric, f double precision, b boolean, "
        "bi bigint, d date, ts timestamptz, iv interval, j jsonb, ba bytea, arr integer[], u uuid)")
    with conn.rw_connection(autocommit=True) as c:
        for i, v in enumerate(AWKWARD):
            c.execute("INSERT INTO master.kinds (id, t) VALUES (%s, %s)", (i, v))
        c.execute(
            "INSERT INTO master.kinds VALUES (100, 'z', 12.50, 1.1, true, 9007199254740993, '2026-11-12', "
            "'2026-11-12 03:36:04.481275+00', '1 year 2 days 03:04:05', '{\"a\": [1, null, \"x\"]}', "
            "'\\xdeadbeef', '{1,2,NULL}', 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11'), "
            "(101, NULL, 'NaN', 'NaN', false, -5, NULL, NULL, NULL, NULL, NULL, NULL, NULL), "
            "(102, '', 0, '-Infinity', NULL, 0, 'infinity', '-infinity', NULL, 'null', '\\x', '{}', NULL)")
    q = "SELECT md5(string_agg(k::text, E'\\n' ORDER BY id)) FROM master.kinds k"
    before = rows(q)
    out = export()
    drop("kinds")
    run_as_plain_sql(out)
    assert rows(q) == before
    assert rows("SELECT count(*) FROM master.kinds") == [(len(AWKWARD) + 3,)]


def test_identity_always_columns_can_be_loaded():
    build("CREATE TABLE master.al (id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v text)",
          "INSERT INTO master.al (v) VALUES ('x'), ('y')")
    out = export()
    assert "OVERRIDING SYSTEM VALUE" in out
    drop("al")
    run_as_plain_sql(out)
    assert rows("SELECT id, v FROM master.al ORDER BY id") == [(1, "x"), (2, "y")]
    assert rows("INSERT INTO master.al (v) VALUES ('z') RETURNING id") == [(3,)]


def test_rows_are_batched_per_statement():
    build("CREATE TABLE master.many (id integer PRIMARY KEY, v text)",
          "INSERT INTO master.many SELECT g, 'v' || g FROM generate_series(1, 1250) g")
    out = export()
    assert out.count('INSERT INTO "master"."many"') == math.ceil(1250 / INSERT_ROWS)
    drop("many")
    run_as_plain_sql(out)
    assert rows("SELECT count(*) FROM master.many") == [(1250,)]


def test_whole_file_is_one_transaction_with_an_end_marker():
    seed()
    out = export()
    body = out.split("\n")
    assert "BEGIN;" in body and body.index("BEGIN;") < body.index("COMMIT;")
    assert out.rstrip().endswith("-- end of export") and out.index("COMMIT;") > out.index("INSERT INTO")


def test_a_second_run_over_existing_tables_fails_and_changes_nothing():
    seed()
    out = export()
    with admin() as c:
        with pytest.raises(Exception, match="already exists"):
            c.execute(out)
        c.execute("ROLLBACK")                                       # a client disconnecting does the same
    assert rows("SELECT count(*) FROM master.parent") == [(2,)]     # not 4


def test_a_cut_off_file_leaves_nothing_behind():
    seed()
    out = export()
    drop("child", "parent")
    cut = out[: out.index("COMMIT;")]                               # the download stopped before the end
    with admin() as c:
        c.execute(cut)
        c.execute("ROLLBACK")
    assert rows("SELECT count(*) FROM information_schema.tables WHERE table_schema = 'master' "
                "AND table_name IN ('parent', 'child')") == [(0,)]


@pytest.mark.parametrize("fmt", ["insert", "copy"])
def test_the_stream_is_batched_not_one_chunk_per_row(fmt):
    build("CREATE TABLE master.big (id integer PRIMARY KEY, v text)",
          "INSERT INTO master.big SELECT g, repeat('x', 40) FROM generate_series(1, 30000) g")
    ex = open_export("master", data=True, cap=10**7, fmt=fmt)
    try:
        chunks = list(ex.chunks())
    finally:
        ex.close()
    total = sum(len(c) for c in chunks)
    assert len(chunks) <= total // BATCH_BYTES + 3                  # ~1.5 MB file, a handful of chunks
    assert all(len(c) <= BATCH_BYTES * 2 for c in chunks[:-1])


def test_copy_format_is_still_there_for_psql():
    seed()
    out = export("copy")
    assert 'COPY "master"."parent" ("id", "name") FROM stdin;\n1\ta\n2\tb\n\\.\n' in out
    assert "-- format: copy" in out and "INSERT INTO" not in out
    assert "psql" in out.split("BEGIN;")[0]                         # the header says to use psql for this one


def test_unknown_format_is_refused():
    with pytest.raises(ExportError) as e:
        open_export("master", data=True, cap=10, fmt="xml")
    assert e.value.status == 400


def test_only_a_few_data_exports_run_at_once():
    seed()
    open_ones = [open_export("master", data=True, cap=100) for _ in range(MAX_CONCURRENT_EXPORTS)]
    try:
        with pytest.raises(ExportError) as e:
            open_export("master", data=True, cap=100)
        assert e.value.status == 429 and "try again" in str(e.value)
        open_export("master", data=False, cap=0).close()            # a structure-only file is cheap: not counted
        open_ones[0].close()
        open_ones[0].close()                                        # closing twice frees one slot, not two
        again = open_export("master", data=True, cap=100)
        again.close()
    finally:
        for ex in open_ones:
            ex.close()
    for _ in range(MAX_CONCURRENT_EXPORTS):
        open_export("master", data=True, cap=100).close()


def test_a_refused_open_gives_its_slot_back():
    seed()
    for _ in range(MAX_CONCURRENT_EXPORTS + 2):
        with pytest.raises(ExportError, match="limit"):
            open_export("master", data=True, cap=1)                 # over the row cap: must not hold a slot


def test_endpoint_format_param():
    from django.test import RequestFactory

    from accounts.models import User
    from schema import views

    seed()
    ed = User.objects.create(username="e@x.com", email="e@x.com", role="editor")

    def call(query):
        req = RequestFactory().get("/api/schema/export" + query)
        req.user = ed
        return views.export(req)

    body = lambda r: b"".join(r.streaming_content)  # noqa: E731
    assert b"FROM stdin" in body(call("?schema=master&data=1&format=copy"))
    assert b"INSERT INTO" in body(call("?schema=master&data=1"))
    assert call("?schema=master&data=1&format=xml").status_code == 400


def test_cut_sql_never_splits_an_insert_statement():
    from mcp_server.tools import cut_sql
    build("CREATE TABLE master.cut (id integer PRIMARY KEY, v text)")
    with conn.rw_connection(autocommit=True) as c:
        for i in range(60):
            c.execute("INSERT INTO master.cut VALUES (%s, %s)", (i, "x;\n'y';" * 3))   # ';' and quotes inside values
    out = export().encode()
    for cap in range(len(out) // 3, len(out) // 3 + 400, 37):
        text, cut = cut_sql(out, cap)
        assert cut and text.endswith(b";\n") or text.endswith(b";")
        body = text.decode()
        assert body.count("'") % 2 == 0                              # never ends inside a string
        last = body.rstrip().rsplit("\n", 1)[-1]
        assert last.endswith(";") and not last.startswith("--")      # ends on a statement end
